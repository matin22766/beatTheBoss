// Converts MediaPipe's canonical_face_model.obj (Apache-2.0) into src/face/canonicalFace.ts.
// Usage: node scripts/gen-face-mesh.mjs path/to/canonical_face_model.obj
// Source: https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2], 'utf8');
const v = [];
const vt = [];
const faces = [];
for (const line of src.split('\n')) {
  const p = line.trim().split(/\s+/);
  if (p[0] === 'v') v.push(p.slice(1, 4).map(Number));
  else if (p[0] === 'vt') vt.push(p.slice(1, 3).map(Number));
  else if (p[0] === 'f') faces.push(p.slice(1).map((q) => q.split('/').map(Number)));
}
const uvOf = new Array(v.length);
const tris = [];
for (const f of faces) {
  for (const [vi, ti] of f) uvOf[vi - 1] = vt[ti - 1];
  tris.push(f.map(([vi]) => vi - 1));
}
const r = (n) => Math.round(n * 10000) / 10000;
const out = `// Generated by scripts/gen-face-mesh.mjs from MediaPipe's canonical_face_model.obj.
// Copyright 2020 The MediaPipe Authors. Licensed under the Apache License, Version 2.0.

/** 468 canonical face vertices (x, y, z) in centimetres, y up, z toward the viewer. */
export const FACE_POSITIONS = new Float32Array([${v.flat().map(r).join(',')}]);
/** Per-vertex texture coordinates (u, v), v up. */
export const FACE_UVS = new Float32Array([${uvOf.flat().map(r).join(',')}]);
/** 898 triangles. */
export const FACE_TRIANGLES = new Uint16Array([${tris.flat().join(',')}]);
`;
writeFileSync('src/face/canonicalFace.ts', out);
console.log(`wrote ${v.length} vertices, ${tris.length} triangles`);
